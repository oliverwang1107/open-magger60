#!/usr/bin/env python3
"""gen_filter_lab_engine.py - make tests/filter_lab_engine.[ch], the FILTER LAB copy of core/src/km_engine.c (M6 task P12b).

The lab compares candidate filters on the REAL engine logic. The engine's two low-pass stages are inlined statements of
km_engine_update() and rapid_general(), so a candidate cannot be tried without changing them. core/src/km_engine.c has exactly one
author in M6 (P12c), so this script derives a copy instead of editing it:

  * every public function gets the prefix lab_ (a #define block in front, so the copy links beside the real engine),
  * the main filter statement   f += ((int32_t)(v << 4) - f) >> KM_ENGINE_FILTER_SHIFT;
    becomes                     f = lab_hook_stage1(f, (int32_t)(v << 4));
  * the rapid-trigger slow stage g += ((f - g) + (1 << (KM_ENGINE_RT_FILTER_SHIFT - 1u))) >> KM_ENGINE_RT_FILTER_SHIFT;
    becomes                     g = lab_hook_stage2(g, f);
  * the rapid-trigger distance floor KM_ENGINE_RT_MIN_MM100 in rt_dist_ok() becomes the variable lab_rt_floor (default 20), so that
    the lab can ask what happens with smaller distances (candidate F3).

With the default hooks (tests/filter_lab.c, filter F0) the copy is bit-identical to the real engine; tests/test_filter_traces.c
proves that on noisy traces. If core/src/km_engine.c changes (P12c), this script stops with "anchor not found" or the proof
fails: regenerate, read the diff, adapt the anchors.

    python firmware/tools/gen_filter_lab_engine.py            # write tests/filter_lab_engine.c and .h
    python firmware/tools/gen_filter_lab_engine.py --check    # exit 1 if the files on disk are not what the engine produces
"""
import re
import sys
from pathlib import Path

FW = Path(__file__).resolve().parents[1]
SRC = FW / "core/src/km_engine.c"
HDR = FW / "core/include/km/km_engine.h"
OUT = FW / "tests/filter_lab_engine.c"
OUT_H = FW / "tests/filter_lab_engine.h"

ANCHORS = [
    ("f += ((int32_t)(v << 4) - f) >> KM_ENGINE_FILTER_SHIFT;",
     "f = lab_hook_stage1(f, (int32_t)(v << 4));"),
    ("g += ((f - g) + (1 << (KM_ENGINE_RT_FILTER_SHIFT - 1u))) >> KM_ENGINE_RT_FILTER_SHIFT;",
     "g = lab_hook_stage2(g, f);"),
    ("return v >= KM_ENGINE_RT_MIN_MM100 && v <= KM_TRAVEL_MM100;",
     "return v >= lab_rt_floor && v <= KM_TRAVEL_MM100;"),
]

PROTO = re.compile(r"^((?:const )?(?:bool|void|unsigned|uint16_t|uint32_t|uint8_t|km_engine_slot_status_t|km_engine_cal_result_t)"
                   r"[ *]+km_engine_[a-z_0-9]+\(.*\);)", re.M)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def public_names(hdr: str):
    names = sorted({re.search(r"(km_engine_[a-z_0-9]+)\(", p).group(1) for p in PROTO.findall(hdr)})
    if len(names) < 18:
        raise SystemExit("could not read the public function names from km_engine.h (%d found)" % len(names))
    return names


def render_c() -> str:
    src = read(SRC)
    names = public_names(read(HDR))
    for old, new in ANCHORS:
        if src.count(old) != 1:
            raise SystemExit("anchor not found exactly once in core/src/km_engine.c: %r (found %d). The engine changed; adapt "
                             "gen_filter_lab_engine.py." % (old, src.count(old)))
        src = src.replace(old, new)
    head = ["/* GENERATED by firmware/tools/gen_filter_lab_engine.py from core/src/km_engine.c - do not edit by hand.",
            " * The filter lab copy of the engine: public functions renamed lab_*, the two filter statements and the rapid-trigger",
            " * distance floor go through the hooks of filter_lab_hooks.h. With the default hooks it behaves exactly like the real engine. */",
            ""]
    head += ["/* the lab copy has no adaptive-gain code of its own: its filters are the hooks */", "#undef KM_ENGINE_FILTER_MODES",
             "#define KM_ENGINE_FILTER_MODES 0", ""]
    head += ["#define %s lab_%s" % (n, n[len("km_"):]) for n in names]
    head += ["", '#include "filter_lab_hooks.h"', ""]
    return "\n".join(head) + "\n" + src


def render_h() -> str:
    hdr = read(HDR)
    names = public_names(hdr)
    protos = PROTO.findall(hdr)
    out = []
    for p in protos:
        for n in names:
            p = p.replace(n + "(", "lab_" + n[len("km_"):] + "(")
        out.append(p)
    return ("/* GENERATED by firmware/tools/gen_filter_lab_engine.py - do not edit by hand. Prototypes of the lab copy of the engine\n"
            " * (tests/filter_lab_engine.c): the functions of km/km_engine.h under the names lab_engine_*; the types are the real ones. */\n"
            "#ifndef FILTER_LAB_ENGINE_H\n#define FILTER_LAB_ENGINE_H\n#include \"km/km_engine.h\"\n\n" + "\n".join(out) +
            "\n\n#endif\n")


def main() -> int:
    outs = ((OUT, render_c()), (OUT_H, render_h()))
    if "--check" in sys.argv:
        bad = 0
        for path, text in outs:
            cur = read(path) if path.exists() else ""
            if cur != text:
                print("%s is out of date; run gen_filter_lab_engine.py" % path.name)
                bad = 1
        if not bad:
            print("filter_lab_engine.[ch] are current")
        return bad
    for path, text in outs:
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
