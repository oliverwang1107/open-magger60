#!/usr/bin/env python3
"""Generate the measured (released, bottom) pairs used by tests/test_depth_model.c.

    python firmware/tools/gen_depth_cal.py            # rewrite firmware/tests/gen/depth_cal_data.h
    python firmware/tools/gen_depth_cal.py --check    # exit 1 when the file on disk is out of date

Source: firmware/core/data/slot_ranges_s2.json (our own measurement on the real keyboard); no vendor data.
"""
import json
import sys
from pathlib import Path

FW = Path(__file__).resolve().parents[1]
SRC = FW / "core/data/slot_ranges_s2.json"
OUT = FW / "tests/gen/depth_cal_data.h"


def render() -> str:
    keys = json.loads(SRC.read_text(encoding="utf-8"))["keys"]
    rows = sorted((int(s), k) for s, k in keys.items())
    out = ["/* GENERATED by firmware/tools/gen_depth_cal.py from core/data/slot_ranges_s2.json - do not edit. */",
           "#ifndef DEPTH_CAL_DATA_H", "#define DEPTH_CAL_DATA_H", "",
           "#define DEPTH_CAL_COUNT %du" % len(rows), "",
           "static const struct { unsigned slot; unsigned released, bottom; } k_depth_cal[DEPTH_CAL_COUNT] = {"]
    for slot, k in rows:
        out.append("    { %d, %d, %d }, /* %s */" % (slot, k["released"], k["bottom"], k["key"].replace("*/", "* /")))
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if cur != text:
            print("out of date:", OUT)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
