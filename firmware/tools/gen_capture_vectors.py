#!/usr/bin/env python3
"""gen_capture_vectors.py - write firmware/tests/golden/capture_vectors.h: scope capture-op packets and the replies of the
PYTHON model of the capture (SimulatedNoiseKeyboard in tools/magger60_noise.py, written from km_scope.h / km_capture.h
independently of the C code). tests/test_capture.c replays every request against the real C code and compares byte for byte;
tools/magger60_noise.py --self-test compares its own packet builder and simulator against the same file.

    python firmware/tools/gen_capture_vectors.py            # rewrite the header
    python firmware/tools/gen_capture_vectors.py --check    # exit 1 if the header on disk is not what the model produces

The capture state every vector starts from (fresh for each request): slots 5 and 12 selected, a finished one-shot run, the third
run since power-up, 100 frames, 10300 cycles apart starting at cycle 1000, value of column c in frame f = (f * 31 + c * 7 + 1000)
& 0xFFF, condition flag set in every 5th frame (f % 5 == 0), 240 cycles per microsecond.
"""
import importlib.util
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("magger60_noise", REPO / "tools/magger60_noise.py")
noise = importlib.util.module_from_spec(spec)
sys.modules["magger60_noise"] = noise
spec.loader.exec_module(noise)
OUT = REPO / "firmware/tests/golden/capture_vectors.h"


def cases():
    R = noise.cap_request
    P = noise.page_request
    return [
        ("status", R(noise.CAP_STATUS, 0)),
        ("status peek len 0", R(noise.CAP_STATUS, 0, 0)),
        ("status len 12 (3 words)", R(noise.CAP_STATUS, 0, 12)),
        ("status start byte is ignored", R(noise.CAP_STATUS, 77)),
        ("select column 2 := slot 20", R(noise.CAP_SELECT | 2, 20)),
        ("select column 0 := slot 75", R(noise.CAP_SELECT | 0, 75)),
        ("select column 1 := end of list (0xFF)", R(noise.CAP_SELECT | 1, 0xFF)),
        ("select slot 76 refused", R(noise.CAP_SELECT | 0, 76)),
        ("select column 4 ignored", R(noise.CAP_SELECT | 4, 3)),
        ("select column 0xFF ignored", R(noise.CAP_SELECT | 0xFF, 3)),
        ("control arm one-shot", R(noise.CAP_CONTROL, 1)),
        ("control arm ring", R(noise.CAP_CONTROL, 2)),
        ("control stop when done", R(noise.CAP_CONTROL, 0)),
        ("control unknown command 9", R(noise.CAP_CONTROL, 9)),
        ("page 0", P(0)),
        ("page 1", P(1)),
        ("page 7 (last, 25 values)", P(7)),
        ("page 8 past the end", P(8)),
        ("page 0 len 10 (2 values)", P(0, 10)),
        ("page 0 len 7 header only", P(0, 7)),
        ("page 0x1FF past the end", P(0x1FF)),
        ("page 0xFFFF past the end", P(0xFFFF)),
        ("unknown op 0xC400", R(0xC400, 0)),
        ("unknown op 0xCF00", R(0xCF00, 0)),
        ("snapshot tag 3 nothing published", noise.scope.build_request(0, 56, 3)),
        ("snapshot start 0 want_tag 0", noise.scope.build_request(0, 56, 0)),
        ("tag just below the capture range 0xBFFF", noise.scope.build_request(0, 56, 0xBFFF)),
        ("tag just above the capture range 0xD000", noise.scope.build_request(0, 56, 0xD000)),
    ]


def render():
    lines = [
        "/* GENERATED by firmware/tools/gen_capture_vectors.py from the Python model of km_scope.h / km_capture.h - do not edit by hand. */",
        "/* Capture ops of the scope channel. Every request starts from the same capture state (see gen_capture_vectors.py). */",
        "#ifndef CAPTURE_VECTORS_H",
        "#define CAPTURE_VECTORS_H",
        "typedef struct { const char *name; const char *req_hex; const char *reply_hex; } capture_vector_t;",
        "static const capture_vector_t capture_vectors[] = {",
    ]
    for name, req in cases():
        sim = noise.vector_keyboard()
        reply = sim.exchange(req)
        lines.append('    { "%s", "%s", "%s" },' % (name, req.hex(), reply.hex()))
    lines += ["};", "#define CAPTURE_VECTOR_COUNT (sizeof capture_vectors / sizeof capture_vectors[0])", "#endif", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if cur != text:
            print("capture_vectors.h is out of date; run gen_capture_vectors.py")
            return 1
        print("capture_vectors.h is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT, len(cases()), "vectors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
