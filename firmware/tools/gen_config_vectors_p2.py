#!/usr/bin/env python3
"""Add the protocol-2 golden vectors (M6 P8) to firmware/tests/golden/config_vectors.h and bring the get_info vector to protocol 2.

The replies are written out byte by byte HERE from CONFIG_PROTOCOL.md; no firmware code and no code of tools/magger60_config.py is
used (only the frame layout: 'U'/0xAA header, checksum = (length + sum of data) & 0xFF). tests/test_config.c replays every vector
against the C implementation, tools/magger60_config.py --self-test against its simulator, ui/tests/config-protocol.test.mjs against
the JavaScript simulated keyboard, so the three implementations are checked against these independent bytes.

Fake backend of the golden run (see test_golden): 100-byte settings (j*3+1), 4 profiles, active profile 2, 76 slots, a 50-byte live
scene (j*5+2), a fixed device status, feature bits 9 and 10 announced.

    python firmware/tools/gen_config_vectors_p2.py          # rewrite the header (idempotent)
    python firmware/tools/gen_config_vectors_p2.py --check  # exit 1 when the header is not what this script writes
"""
import re
import sys
import zlib
from pathlib import Path

HEADER = Path(__file__).resolve().parents[1] / "tests/golden/config_vectors.h"
BEGIN = "    /* ---- protocol 2 (M6 P8): generated by firmware/tools/gen_config_vectors_p2.py ---- */\n"

SCENE = bytes((j * 5 + 2) & 0xFF for j in range(50))
DEVST = bytes([2, 1, 0, 0x09, 2, 1, 2, 0, 0x34, 0x12, 3, 0, 7, 0, 0, 0])
FEATURES = 0x3F | 0x80 | 0x100 | 0x200 | 0x400


def frame(head, data):
    p = bytearray(64)
    p[0], p[1] = head, 0xC6
    p[3] = (len(data) + sum(data)) & 0xFF
    p[4] = len(data)
    p[8:8 + len(data)] = data
    return bytes(p)


def req(op, token, args=b""):
    return frame(0x55, bytes([op, token]) + bytes(args))


def rep(op, token, status, payload=b""):
    return frame(0xAA, bytes([op, token, status]) + bytes(payload))


def le16(v):
    return bytes([v & 255, v >> 8])


def le32(v):
    return le16(v & 0xFFFF) + le16(v >> 16)


def vectors():
    v = []
    # group 21: DEVICE_STATUS
    v.append(("device_status", 21, req(0x0A, 0x70), rep(0x0A, 0x70, 0, DEVST)))
    v.append(("device_status with an argument", 22, req(0x0A, 0x71, b"\x00"), rep(0x0A, 0x71, 2)))
    # group 23: scene read, the first page (44 bytes) and the last (6 bytes) from one snapshot (id 1)
    crc = zlib.crc32(SCENE) & 0xFFFFFFFF
    v.append(("scene_get page 0", 23, req(0x30, 0x72, le16(0) + bytes([44, 0])),
              rep(0x30, 0x72, 0, bytes([1]) + le16(50) + le32(crc) + le16(0) + SCENE[:44])))
    v.append(("scene_get last page (6 bytes)", 23, req(0x30, 0x73, le16(44) + bytes([44, 1])),
              rep(0x30, 0x73, 0, bytes([1]) + le16(50) + le32(crc) + le16(44) + SCENE[44:])))
    v.append(("scene_get stale id", 24, req(0x30, 0x74, le16(44) + bytes([44, 9])), rep(0x30, 0x74, 7)))
    # group 25: scene write sequence
    blob = bytes(range(0x40, 0x4A))                       # 10 bytes
    c = zlib.crc32(blob) & 0xFFFFFFFF
    v.append(("scene_begin 10", 25, req(0x31, 0x75, le16(10)), rep(0x31, 0x75, 0, le16(1024))))
    v.append(("scene_page 0..9", 25, req(0x32, 0x76, le16(0) + blob), rep(0x32, 0x76, 0, le16(10))))
    v.append(("scene_commit ok", 25, req(0x33, 0x77, b"LITE" + le16(10) + le32(c)), rep(0x33, 0x77, 0, le32(1))))
    v.append(("scene_commit again", 25, req(0x33, 0x78, b"LITE" + le16(10) + le32(c)), rep(0x33, 0x78, 9)))
    # group 26..29: refusals
    v.append(("scene_commit without the word", 26, req(0x33, 0x79, b"\0\0\0\0" + le16(10) + le32(c)), rep(0x33, 0x79, 5)))
    v.append(("scene_commit with the settings word", 27, req(0x33, 0x7A, b"SAVE" + le16(10) + le32(c)), rep(0x33, 0x7A, 5)))
    v.append(("scene_begin 1025", 28, req(0x31, 0x7B, le16(1025)), rep(0x31, 0x7B, 8)))
    v.append(("scene_page nothing staged", 29, req(0x32, 0x7C, le16(0) + b"\x01"), rep(0x32, 0x7C, 9)))
    return v


def get_info_reply():
    payload = bytes([2, 4, 2]) + le16(8192) + bytes([44, 52]) + le16(FEATURES) + bytes([0]) + le16(0) + le16(0) + le32(0) + le16(1024)
    return rep(0x01, 0x11, 0, payload)


def render(text):
    # drop an earlier generated block
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index("};", a)
        text = text[:a] + text[b:]
    # protocol-2 get_info reply
    m = re.search(r'(\{ "get_info", 1, "[0-9a-f]+", ")([0-9a-f]+)(" \},)', text)
    assert m, "the get_info vector is missing"
    text = text[:m.start(2)] + get_info_reply().hex() + text[m.end(2):]
    lines = [BEGIN]
    for name, group, rq, rp in vectors():
        lines.append('    { "%s", %d, "%s", "%s" },\n' % (name, group, rq.hex(), rp.hex()))
    return text.replace("};\n#define CONFIG_VECTOR_COUNT", "".join(lines) + "};\n#define CONFIG_VECTOR_COUNT", 1)


def main():
    raw = HEADER.read_bytes()
    crlf = b"\r\n" in raw
    text = raw.decode("utf-8").replace("\r\n", "\n")
    out = render(text)
    out_b = (out.replace("\n", "\r\n") if crlf else out).encode("utf-8")
    if "--check" in sys.argv:
        if out_b != raw:
            print("config_vectors.h is out of date; run firmware/tools/gen_config_vectors_p2.py")
            return 1
        print("config_vectors.h is current (%d vectors)" % out.count("\n    { \""))
        return 0
    HEADER.write_bytes(out_b)
    print("wrote %s" % HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())
