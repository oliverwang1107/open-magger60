#!/usr/bin/env python3
"""Generate the sensor slot table core/gen/km_slot_data.c.

    python firmware/tools/gen_slotmap.py            # rewrite the file
    python firmware/tools/gen_slotmap.py --check    # exit 1 when the file on disk is out of date

Inputs (both are our own data, nothing from the vendor):
  firmware/core/data/slotmap_measured.json   slot -> key name, measured on the keyboard (one press per key)
  firmware/port/n32h48x/sense_tables.c       the ADC channel lists of the hardware (regular and injected)
From the slot number and the channel lists the table gets, for every slot: mux phase, ADC 1-4, rank and channel.
Slot s = 2 * word + half; words 0..35 are 4 phases x 9 words (words 0-5 of a phase: half 0 = ADC1, half 1 = ADC2,
words 6-8: half 0 = ADC3, half 1 = ADC4), words 36/37 are the injected channels (slots 72..75 = ADC1..ADC4).
The generated file is a normal committed source; tests/test_scan.c checks it against the JSON again.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FW = ROOT / "firmware"
OUT_C = FW / "core/gen/km_slot_data.c"
MEASURED = FW / "core/data/slotmap_measured.json"
SENSE_C = FW / "port/n32h48x/sense_tables.c"

PHASE_INJ = 4  # km_slot_info_t.phase of the injected slots (KM_SCAN_PHASE_INJ)
SLOTS = 76


def _body(text, name):
    """The initializer text of `const uint8_t name[...] = { ... };` without comments."""
    m = re.search(name + r"\s*(?:\[[^\]]*\])+\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit("cannot find %s in %s" % (name, SENSE_C))
    return re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)


def load_channels():
    """(regular[4][...], injected[4]) from sense_tables.c; padding past sense_regular_len is dropped."""
    text = SENSE_C.read_text(encoding="utf-8")
    rows = [[int(x) for x in r.split(",") if x.strip()] for r in re.findall(r"\{([^{}]*)\}", _body(text, "sense_regular_ch"))]
    lens = [int(x) for x in re.sub(r"/\*.*?\*/", "", _body(text, "sense_regular_len")).replace("\n", " ").split(",") if x.strip()]
    inj = [int(x) for x in _body(text, "sense_injected_ch").replace("\n", " ").split(",") if x.strip()]
    if len(rows) != 4 or len(lens) != 4 or len(inj) != 4 or lens != [6, 6, 3, 3]:
        raise SystemExit("unexpected channel lists in %s: %r %r %r" % (SENSE_C, rows, lens, inj))
    return [r[:n] for r, n in zip(rows, lens)], inj


def source_of(slot, regular, inj):
    """(phase, adc, rank, channel) of a slot, computed from the slot number and the channel lists."""
    word, half = divmod(slot, 2)
    if word >= 36:
        n = half + 2 * (word - 36)
        return PHASE_INJ, n + 1, 1, inj[n]
    phase, k = divmod(word, 9)
    if k < 6:
        return phase, 1 + half, k + 1, regular[half][k]
    return phase, 3 + half, k - 5, regular[2 + half][k - 6]


def load_rows():
    keys = json.loads(MEASURED.read_text(encoding="utf-8"))["slots"]
    regular, inj = load_channels()
    rows = []
    for s in range(SLOTS):
        phase, adc, rank, ch = source_of(s, regular, inj)
        name = keys.get(str(s))
        rows.append({"slot": s, "key": name if name is not None else "(unassigned)", "assigned": name is not None,
                     "phase": phase, "adc": adc, "rank": rank, "channel": ch})
    return rows


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_c(rows):
    lines = [
        "/* GENERATED by firmware/tools/gen_slotmap.py - do not edit; run the tool again after changing its inputs:",
        " * firmware/core/data/slotmap_measured.json (slot -> key, measured on the keyboard) and the channel lists in",
        " * firmware/port/n32h48x/sense_tables.c (slot -> mux phase / ADC / rank / channel). */",
        '#include "km/km_scan.h"',
        "",
        "const km_slot_info_t km_slot_table[KM_NUM_SLOTS] = {",
        "    /* phase, adc, rank, channel, assigned, key */",
    ]
    for r in rows:
        lines.append("    { %d, %d, %d, %d, %s, %s }, /* %d */" % (
            r["phase"], r["adc"], r["rank"], r["channel"], "true" if r["assigned"] else "false",
            c_string(r["key"]), r["slot"]))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    text = render_c(load_rows())
    if "--check" in sys.argv:
        bad = not OUT_C.exists() or OUT_C.read_text(encoding="utf-8") != text    # read_text folds CRLF checkouts
        if bad:
            print("out of date:", OUT_C, file=sys.stderr)
        print("slot table", "OUT OF DATE" if bad else "up to date")
        return 1 if bad else 0
    OUT_C.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT_C)
    return 0


if __name__ == "__main__":
    sys.exit(main())
